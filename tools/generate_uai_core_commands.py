from __future__ import annotations

import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

CLI_ROOT = Path(__file__).resolve().parents[1] / "cli"
if str(CLI_ROOT) not in sys.path:
    sys.path.insert(0, str(CLI_ROOT))

from uai_core.command_manifest import DEPRECATED_ALLOWED_USE_CASES, build_command_manifest  # noqa: E402

COMMANDS_ROOT = CLI_ROOT / "uai_core" / "commands"
DEPRECATED_ROOT = COMMANDS_ROOT / "deprecated"
GENERATED_HEADER = "# Generated by UeAgentInterfaceCMD/tools/generate_uai_core_commands.py.\n# Do not edit generated command wrapper modules manually.\n"


def module_name_from_doc(doc_file: str) -> str:
    stem = Path(doc_file).stem
    stem = re.sub(r"^\d+_?", "", stem)
    stem = stem.replace("-", "_")
    stem = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", stem)
    stem = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", stem)
    stem = re.sub(r"[^a-zA-Z0-9_]+", "_", stem).lower()
    stem = re.sub(r"_+", "_", stem).strip("_")
    return stem or "misc"


def command_group_key(command: dict[str, Any]) -> tuple[bool, str]:
    doc_file = str(command.get("doc_file") or "")
    deprecated = bool(command.get("deprecated")) or "/deprecatedCommand/" in doc_file
    return deprecated, module_name_from_doc(doc_file)


def clean_text(value: Any) -> str:
    text = str(value or "").strip()
    text = re.sub(r"\s+", " ", text)
    return text.replace('"""', '\"\"\"')


def list_text(values: Any, *, empty: str) -> str:
    if not isinstance(values, list) or not values:
        return empty
    return ", ".join(str(value) for value in values)


def replacement_text(values: Any) -> str:
    if not isinstance(values, list) or not values:
        return "\u65e0\u81ea\u52a8\u8bb0\u5f55\uff1b\u8be6\u89c1\u5e9f\u5f03\u547d\u4ee4\u6587\u6863\u3002"
    return ", ".join(str(value) for value in values)


def function_docstring(command: dict[str, Any], *, deprecated: bool) -> str:
    command_name = str(command["name"])
    description = clean_text(command.get("description")) or f"\u6267\u884c UAI \u6307\u4ee4 `{command_name}`\u3002"
    doc_file = str(command.get("doc_file") or "")
    inputs = list_text(
        command.get("params"),
        empty="\u65e0\u6587\u6863\u53c2\u6570\uff1b\u4f7f\u7528 **params \u4f20\u5165 UAI \u53c2\u6570\u3002",
    )
    return_hint = list_text(command.get("returns"), empty="")
    output = "\u8f93\u51fa: CommandResult\uff1bUAI response \u5728 CommandResult.response\u3002"
    if deprecated:
        replacement = replacement_text(command.get("replacement"))
        doc_lines = [
            f"Deprecated: {description}",
            "",
            f"\u8f93\u5165: {inputs}",
            output,
            f"\u66ff\u4ee3: {replacement}",
            f"\u6587\u6863: {doc_file}",
        ]
    else:
        doc_lines = [
            description,
            "",
            f"\u8f93\u5165: {inputs}",
            output,
            f"\u6587\u6863: {doc_file}",
        ]
    if return_hint:
        doc_lines.insert(-1, f"\u8fd4\u56de\u5b57\u6bb5\u63d0\u793a: {return_hint}")
    body = "\n    ".join(doc_lines)
    return f'    """{body}"""\n'

def render_function(command: dict[str, Any], *, deprecated: bool) -> str:
    command_name = str(command["name"])
    doc = function_docstring(command, deprecated=deprecated)
    if deprecated:
        return (
            f"def {command_name}(\n"
            "    ue: UaiCore,\n"
            "    *,\n"
            "    deprecated_use_case: DeprecatedUseCase,\n"
            "    request_id: str | None = None,\n"
            "    preflight: bool = True,\n"
            "    **params: Any,\n"
            ") -> CommandResult:\n"
            f"{doc}"
            f"    return execute_deprecated_command(\n"
            f"        ue,\n"
            f"        {command_name!r},\n"
            f"        params,\n"
            f"        deprecated_use_case=deprecated_use_case,\n"
            f"        request_id=request_id,\n"
            f"        preflight=preflight,\n"
            f"    )\n"
        )
    return (
        f"def {command_name}(\n"
        "    ue: UaiCore,\n"
        "    *,\n"
        "    request_id: str | None = None,\n"
        "    preflight: bool = True,\n"
        "    **params: Any,\n"
        ") -> CommandResult:\n"
        f"{doc}"
        f"    return execute_command(ue, {command_name!r}, params, request_id=request_id, preflight=preflight)\n"
    )


def render_module(module_name: str, commands: list[dict[str, Any]], *, deprecated: bool) -> str:
    names = [str(command["name"]) for command in commands]
    if deprecated:
        imports = "from ...api import CommandResult, UaiCore\nfrom .._helpers import DeprecatedUseCase, execute_deprecated_command\n"
    else:
        imports = "from ..api import CommandResult, UaiCore\nfrom ._helpers import execute_command\n"
    parts = [
        GENERATED_HEADER,
        "from __future__ import annotations\n\n",
        "from typing import Any\n\n",
        imports,
        "\n",
        f"__all__ = {names!r}\n\n\n",
    ]
    for command in commands:
        parts.append(render_function(command, deprecated=deprecated))
        parts.append("\n\n")
    return "".join(parts)


def render_helpers() -> str:
    use_cases = list(DEPRECATED_ALLOWED_USE_CASES)
    literal_items = ", ".join(repr(value) for value in use_cases)
    return (
        GENERATED_HEADER
        + "from __future__ import annotations\n\n"
        + "from typing import Any, Literal\n\n"
        + "from ..api import CommandResult, UaiCore\n\n"
        + f"DeprecatedUseCase = Literal[{literal_items}]\n\n"
        + "__all__ = [\"DeprecatedUseCase\", \"execute_command\", \"execute_deprecated_command\"]\n\n\n"
        + "def execute_command(\n"
        + "    ue: UaiCore,\n"
        + "    command: str,\n"
        + "    params: dict[str, Any],\n"
        + "    *,\n"
        + "    request_id: str | None = None,\n"
        + "    preflight: bool = True,\n"
        + ") -> CommandResult:\n"
        + "    return ue.exec(command, dict(params), request_id=request_id, preflight=preflight)\n\n\n"
        + "def execute_deprecated_command(\n"
        + "    ue: UaiCore,\n"
        + "    command: str,\n"
        + "    params: dict[str, Any],\n"
        + "    *,\n"
        + "    deprecated_use_case: DeprecatedUseCase,\n"
        + "    request_id: str | None = None,\n"
        + "    preflight: bool = True,\n"
        + ") -> CommandResult:\n"
        + "    return ue.exec(\n"
        + "        command,\n"
        + "        dict(params),\n"
        + "        request_id=request_id,\n"
        + "        preflight=preflight,\n"
        + "        allow_deprecated=True,\n"
        + "        deprecated_use_case=deprecated_use_case,\n"
        + "    )\n"
    )


def render_package_init(module_names: list[str], *, deprecated: bool) -> str:
    title = "Deprecated UAI command wrapper modules." if deprecated else "UAI command wrapper modules grouped by command docs."
    lines = [
        GENERATED_HEADER,
        f'"""{title}"""\n\n',
        f"__all__ = {module_names!r}\n",
    ]
    return "".join(lines)


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def clear_generated_tree() -> None:
    if COMMANDS_ROOT.exists():
        for path in COMMANDS_ROOT.iterdir():
            if path.name == "__pycache__":
                shutil.rmtree(path)
            elif path.is_file() and path.suffix == ".py":
                path.unlink()
            elif path.is_dir() and path.name == "deprecated":
                shutil.rmtree(path)
    DEPRECATED_ROOT.mkdir(parents=True, exist_ok=True)


def main() -> int:
    manifest = build_command_manifest()
    command_items = list((manifest.get("commands") or {}).values())
    groups: dict[tuple[bool, str], list[dict[str, Any]]] = defaultdict(list)
    for item in command_items:
        if not isinstance(item, dict):
            continue
        doc_file = str(item.get("doc_file") or "")
        if not doc_file:
            continue
        groups[command_group_key(item)].append(item)

    clear_generated_tree()
    write_text(COMMANDS_ROOT / "_helpers.py", render_helpers())

    active_modules: list[str] = []
    deprecated_modules: list[str] = []
    for (is_deprecated, module_name), commands in sorted(groups.items(), key=lambda item: (item[0][0], item[0][1])):
        sorted_commands = sorted(commands, key=lambda command: str(command["name"]))
        if is_deprecated:
            deprecated_modules.append(module_name)
            write_text(DEPRECATED_ROOT / f"{module_name}.py", render_module(module_name, sorted_commands, deprecated=True))
        else:
            active_modules.append(module_name)
            write_text(COMMANDS_ROOT / f"{module_name}.py", render_module(module_name, sorted_commands, deprecated=False))

    write_text(COMMANDS_ROOT / "__init__.py", render_package_init(active_modules, deprecated=False))
    write_text(DEPRECATED_ROOT / "__init__.py", render_package_init(deprecated_modules, deprecated=True))
    print(
        f"generated active_modules={len(active_modules)} deprecated_modules={len(deprecated_modules)} "
        f"commands={sum(len(v) for v in groups.values())}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
